def api_request(url, data=None, method="GET"):
    headers = {"User-Agent": "curl/8.0"}
    if data is not None:
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, method=method, headers=headers)
    with urllib.request.urlopen(req) as resp:
        return json.load(resp), resp.status


def fetch_exam():
    result, _ = api_request(f"{API_BASE}/api/exams/{EXAM_ID}")
    return result["exam"]


def replace_translation(problem_text: str, new_translation: str) -> str:
    if "{{全訳}}" not in problem_text:
        raise ValueError("{{全訳}} section not found")
    before, rest = problem_text.split("{{全訳}}", 1)
    for marker in ("{{解説}}", "{{設問}}"):
        if marker in rest:
            _, tail = rest.split(marker, 1)
            return before + "{{全訳}}\n\n" + new_translation.strip() + "\n\n" + marker + tail
    return before + "{{全訳}}\n\n" + new_translation.strip() + "\n\n" + rest.lstrip("\n")


def main():
    exam = fetch_exam()
    updates = []
    for q in exam["questions"]:
        qnum = q["question_number"]
        if qnum not in TRANSLATIONS:
            continue
        new_problem = replace_translation(q["problem_text"], TRANSLATIONS[qnum])
        updates.append({
            "questionNumber": qnum,
            "category": q.get("category", ""),
            "problemText": new_problem,
            "answerText": q["answer_text"],
            "commentaryText": q["commentary_text"],
        })
        print(f"Q{qnum}: translation {len(TRANSLATIONS[qnum])} chars")

    payload = json.dumps({"questions": updates}).encode("utf-8")
    result, status = api_request(
        f"{API_BASE}/api/exams/{EXAM_ID}",
        data=payload,
        method="PUT",
    )
    print("Update OK:", status)
    print(json.dumps(result, ensure_ascii=False, indent=2)[:500])


if __name__ == "__main__":
    main()
